#!/bin/sh
# Creates or updates deploy/local/.env with random credentials for the local
# stack. deploy/local/.env is git-ignored. Existing values are kept; missing ones
# are added. Re-run with --force to rotate everything.
#
# Use it from your shell too:  set -a; . deploy/local/.env; set +a
set -eu
dir=$(cd "$(dirname "$0")" && pwd)
out="$dir/.env"
rand() { od -An -N24 -tx1 /dev/urandom | tr -d ' \n'; }
# OpenSearch requires upper, lower, digit and special characters.
strong() { printf 'Bd1!%s' "$(rand)"; }
umask 077
if [ "${1:-}" = "--force" ] || [ ! -e "$out" ]; then
  echo "# Local-only credentials generated by deploy/local/dev-env.sh. Do not commit." > "$out"
fi
have() { grep -q "^$1=" "$out"; }
add() { have "$1" || { printf '%s=%s\n' "$1" "$2" >> "$out"; echo "added $1"; }; }

key="bd_test_$(rand)"
have BINDLE_API_KEY && key=$(sed -n 's/^BINDLE_API_KEY=//p' "$out")
add BINDLE_API_KEY "$key"
add BINDLE_API_KEYS "$key=dev-tenant"
add BINDLE_ENDPOINT "http://localhost:4318"
add OPENSEARCH_ADMIN_PASSWORD "$(strong)"
add BINDLE_SEARCH_WRITER_PASSWORD "$(strong)"
add BINDLE_SEARCH_READER_PASSWORD "$(strong)"
add POSTGRES_PASSWORD "$(rand)"
add BINDLE_CONTROL_API_PASSWORD "$(rand)"
add BINDLE_CONTROL_INGEST_PASSWORD "$(rand)"
add BINDLE_CONTROL_ALERTS_PASSWORD "$(rand)"
# Local-only: the query API on 127.0.0.1:8080 serves every request as this
# tenant until real console auth exists. Remove the line to make it reject all.
add BINDLE_API_DEV_AUTH_BYPASS_TENANT "dev-tenant"
# No longer used.
sed -i.bak -E '/^(CLICKHOUSE_PASSWORD|BINDLE_DB_WRITER_PASSWORD|BINDLE_DB_READER_PASSWORD)=/d' "$out" && rm -f "$out.bak"
echo "ok: $out"
